#!/usr/bin/env python3
"""Write bunun63_pairs.tsv: which record of sentence/Bunun_Isbukun/63.json repeats
which record of another Bunun sentence file.

63.json is NTU's '63_revised.json' (source_release.tsv): a revised copy of the
Bunun sentence collection, published by NTU alongside the original files. 875
of its 920 records repeat a record elsewhere. A record is paired with another
file's record when their word lists are identical, or else when they share a
translation and their word lists are at least 60% alike (difflib ratio) -- the
revision often changes only the analysis notation (ma<ba>baliv -> ma-ba-baliv).

The pairs only say which sentences are copies of each other. What happens to
each pair is decided at build time, on the cleaned sentences, by
dedupe_bunun63.py (rulings 2026-10-16).

usage: python make_bunun63_pairs.py
"""
from __future__ import annotations

import collections
import csv
import difflib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE.parent / "sentence" / "Bunun_Isbukun"


def records(p: Path) -> list:
    d = json.loads(p.read_text(encoding="utf-8"))
    recs = d if isinstance(d, list) else list(d.values())[0]
    return [r for r in recs if isinstance(r, list) and len(r) > 1 and isinstance(r[1], dict)]


def norm(s) -> str:
    return " ".join(str(s).replace("’", "'").replace("‘", "'").replace("&lt;", "<").replace("&gt;", ">").split())


def words(r) -> tuple:
    return tuple(norm(g[0]) for g in r[1].get("gloss") or [] if g)


def translations(r) -> list:
    return [norm(l[2:]) for l in r[1].get("free") or [] if str(l)[:2] in ("#c", "#e") and norm(l[2:])]


def main() -> int:
    by_words, by_tr = {}, collections.defaultdict(list)
    for p in sorted(SRC.glob("*.json")):
        if p.name == "63.json":
            continue
        for r in records(p):
            by_words.setdefault(words(r), (p.stem, r))
            for t in translations(r):
                by_tr[t].append((p.stem, r))
    rows = []
    for r in records(SRC / "63.json"):
        hit, how = by_words.get(words(r)), "words"
        if hit is None:
            how, best = "translation+similar words", None
            for stem, o in {(s, o[0]): (s, o) for t in translations(r) for s, o in by_tr.get(t, [])}.values():
                ratio = difflib.SequenceMatcher(None, " ".join(words(r)), " ".join(words(o))).ratio()
                if best is None or ratio > best[0]:
                    best = (ratio, stem, o)
            hit = (best[1], best[2]) if best and best[0] >= 0.6 else None
        if hit:
            rows.append([str(r[0]), hit[0], str(hit[1][0]), how])
    with open(HERE / "bunun63_pairs.tsv", "w", encoding="utf-8", newline="") as fh:
        fh.write("# 63.json records and the record of another Bunun sentence file they repeat.\n"
                 "# Generated by make_bunun63_pairs.py; do not edit by hand.\n")
        w = csv.writer(fh, delimiter="\t", lineterminator="\n")
        w.writerow(["record_63", "other_file", "other_record", "matched_on"])
        w.writerows(rows)
    print(f"wrote {len(rows)} pairs")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
