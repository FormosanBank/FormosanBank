#!/usr/bin/env python3
"""Write audio_timing_grafts.tsv: per-record audio timing for three stories
whose text NTU publishes twice.

NTU's release has two transcriptions of each of these recordings. The build
takes the newer text, which has no audio timing; the older one is timed record
by record (source_release.tsv lists it as 'excluded'). Ruling 2026-10-16
("C: newer text + timing from the audio version", all three): the newer text
keeps its words, glosses and translations, and takes each record's time span
and recording from the timed version. The two versions have the same record ids
in the same order and the same sentence ends, which this script checks.

The timed files are not committed; this script downloads them from the pinned
release, checks each against the sha256 in source_release.tsv, and writes only
the timing. Run it again only if the pinned release changes.

usage: python make_audio_timing_grafts.py
"""
from __future__ import annotations

import csv
import hashlib
import json
import sys
import urllib.parse
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
CODEDOCS = HERE.parent
PAIRS = [  # (used file, timed file) -- both NTU release paths
    ("story/Seediq_Tgdaya/sdqNr-taboo_pawan 2021s.json", "story/Seediq_Tgdaya/sdqNr-taboo_pawan.json"),
    ("story/Seediq_Tgdaya/sdqNr-tattoo2_pawan 2020s.json", "story/Seediq_Tgdaya/sdqNr-tattoo2_pawan.json"),
    ("story/Tsou_Tsou/TsouNr-pear-story-3.json", "story/Tsou_Tsou/TsouNr-pear-zheng-2.json"),
]
REPO = "liao961120/glossParser"


def release_commit() -> str:
    """The pinned gh-pages commit, from source_release.tsv's header."""
    text = (CODEDOCS / "source_release.tsv").read_text(encoding="utf-8")
    start = text.index("commit ") + len("commit ")
    return text[start:start + 40]


def pinned_sha(upstream: str) -> str:
    rows = [l for l in (CODEDOCS / "source_release.tsv").read_text(encoding="utf-8").splitlines()
            if l and not l.startswith("#")]
    for r in csv.DictReader(rows, delimiter="\t"):
        if r["upstream_path"] == upstream:
            return r["sha256"]
    raise SystemExit(f"{upstream} is not in source_release.tsv")


def records(data) -> list:
    recs = data if isinstance(data, list) else list(data.values())[0]
    return [r for r in recs if isinstance(r, list) and len(r) > 1 and isinstance(r[1], dict)]


def main() -> int:
    commit = release_commit()
    out = [["source_file", "record", "start", "end", "video", "timing_from"]]
    for used, timed in PAIRS:
        url = f"https://raw.githubusercontent.com/{REPO}/{commit}/{urllib.parse.quote(timed)}"
        raw = urllib.request.urlopen(url, timeout=60).read()
        if hashlib.sha256(raw).hexdigest() != pinned_sha(timed):
            raise SystemExit(f"{timed}: sha256 does not match source_release.tsv")
        A = records(json.loads((CODEDOCS / used).read_text(encoding="utf-8")))
        B = records(json.loads(raw.decode("utf-8")))
        if [a[0] for a in A] != [b[0] for b in B]:
            raise SystemExit(f"{used}: record ids differ from {timed}")
        if [bool(a[1].get("s_end")) for a in A] != [bool(b[1].get("s_end")) for b in B]:
            raise SystemExit(f"{used}: sentence ends differ from {timed}")
        for a, b in zip(A, B):
            span = b[1].get("iu_a_span") or [None, None]
            video = (b[1].get("meta") or {}).get("video")
            if span[0] is None or not video:
                continue
            out.append([used, str(a[0]), str(span[0]), str(span[1]), video, timed])
    header = ("# Audio timing grafted onto records with no timing of their own (ruling 2026-10-16, C).\n"
              "# Generated by make_audio_timing_grafts.py from NTU's release; do not edit by hand.\n")
    with open(HERE / "audio_timing_grafts.tsv", "w", encoding="utf-8", newline="") as fh:
        fh.write(header)
        csv.writer(fh, delimiter="\t", lineterminator="\n").writerows(out)
    print(f"wrote {len(out) - 1} rows")
    return 0


if __name__ == "__main__":
    sys.exit(main())
