def _tier(parent, tag, kind):
    return next(
        (child for child in parent.findall(tag)
         if child.get("kindOf") == kind),
        None,
    )


def _translation(parent, lang):
    return next(
        (child for child in parent.findall("TRANSL")
         if child.get(_XLANG) == lang and child.get("ver") is None),
        None,
    )


def _append_note(form, note):
    existing = (form.get("notes") or "").strip()
    if note in existing:
        return
    form.set("notes", f"{existing}; {note}" if existing else note)


def _remove_phon(sentence):
    for phon in list(sentence.xpath(".//PHON")):
        phon.getparent().remove(phon)


def _strip_parens(text):
    return (text or "").replace("(", "").replace(")", "")


def _strip_sentence_notation(sentence, note):
    changed = False
    for element in sentence.xpath(".//FORM | .//TRANSL"):
        if element.text and ("(" in element.text or ")" in element.text):
            element.text = _strip_parens(element.text)
            changed = True
        notes = element.get("notes")
        if notes and ("(" in notes or ")" in notes):
            # Notes are evidence, not validator input.  Do not rewrite them.
            continue
    if changed:
        original = _tier(sentence, "FORM", "original")
        if original is not None:
            _append_note(original, note)
        _remove_phon(sentence)
    return changed


def _set_form(parent, value):
    for kind in ("original", "standard"):
        form = _tier(parent, "FORM", kind)
        if form is not None:
            form.text = value


def _set_primary_translation(parent, lang, value):
    element = _translation(parent, lang)
    if element is None:
        element = etree.Element("TRANSL")
        element.set(_XLANG, lang)
        first_word = parent.find("W")
        if first_word is None:
            parent.append(element)
        else:
            parent.insert(parent.index(first_word), element)
    element.text = value


def _add_alt_translation(parent, lang, value):
    for element in parent.findall("TRANSL"):
        if element.get(_XLANG) == lang and (element.text or "") == value:
            if element is not _translation(parent, lang):
                element.set("ver", "alt")
            return
    element = etree.Element("TRANSL")
    element.set(_XLANG, lang)
    element.set("ver", "alt")
    element.text = value
    words = parent.findall("W")
    insert_at = parent.index(words[0]) if words else len(parent)
    parent.insert(insert_at, element)


def _make_word(sid, index, form, eng, zho, *, form_note=None):
    word = etree.Element("W", id=f"{sid}_W{index}")
    original = etree.SubElement(word, "FORM", kindOf="original")
    original.text = form
    if form_note:
        original.set("notes", form_note)
    standard = etree.SubElement(word, "FORM", kindOf="standard")
    standard.text = form
    zho_t = etree.SubElement(word, "TRANSL")
    zho_t.set(_XLANG, "zho")
    zho_t.text = zho
    eng_t = etree.SubElement(word, "TRANSL")
    eng_t.set(_XLANG, "eng")
    eng_t.text = eng
    morph = etree.SubElement(word, "M", id=f"{sid}_W{index}M1")
    m_original = etree.SubElement(morph, "FORM", kindOf="original")
    m_original.text = form
    m_standard = etree.SubElement(morph, "FORM", kindOf="standard")
    m_standard.text = form
    m_eng = etree.SubElement(morph, "TRANSL")
    m_eng.set(_XLANG, "eng")
    m_eng.text = eng
    m_zho = etree.SubElement(morph, "TRANSL")
    m_zho.set(_XLANG, "zho")
    m_zho.text = zho
    return word


def _fix_saisiyat_column_shift(sentence):
    sid = sentence.get("id")
    if sid != "SaiNr-election_lahi_ a taro_ babay_S_48":
        return False
    words = sentence.findall("W")
    if len(words) < 8 or "money(ita'" not in (
            _tier(words[7], "FORM", "original").text or ""):
        return False

    source_form = "So min'itol ma' noka a moto nasia money(ita'."
    corrected = "So min'itol ma' noka a moto nasia hayza' ka biyae'."
    _set_form(sentence, corrected)
    original = _tier(sentence, "FORM", "original")
    _append_note(
        original,
        "source JSON row 115 uses ori tokens hayza' ka biyae'; the raw "
        "misaligned gloss cell money_(ita' | AF.diligent | 主焦.勤奮 is "
        "preserved here as an audit note; prior generated FORM was "
        f"{source_form}",
    )

    template = words[7]
    position = sentence.index(template)
    tail = template.tail
    sentence.remove(template)
    entries = [
        ("hayza'", "EXIST", "存在", None),
        ("ka", "NOM", "主格", None),
        (
            "biyae'",
            "money",
            "錢",
            "raw source gloss cell: money_(ita' | AF.diligent | 主焦.勤奮",
        ),
    ]
    for offset, (form, eng, zho, note) in enumerate(entries):
        word = _make_word(sid, 7 + offset, form, eng, zho, form_note=note)
        word.tail = tail
        sentence.insert(position + offset, word)
    _remove_phon(sentence)
    return True


def _fix_voiceover_label(sentence):
    if sentence.get("id") != "KavNr-frog_abas_S_80":
        return False
    original = _tier(sentence, "FORM", "original")
    if original is None or "VOICEOVER" not in (original.text or ""):
        return False
    _set_form(sentence, "maiti.")
    _append_note(original, "source transcription label removed from FORM: VOICEOVER")
    word = sentence.find("W")
    _set_form(word, "mai=ti")
    morphs = word.findall("M")
    if len(morphs) != 2:
        raise AssertionError("KavNr-frog_abas_S_80 no longer has two morphemes")
    _set_form(morphs[0], "mai")
    _set_form(morphs[1], "=ti")
    _remove_phon(sentence)
    return True


def _fix_rarely_used_annotation(sentence):
    if sentence.get("id") != "3_S_458":
        return False
    original = _tier(sentence, "FORM", "original")
    if original is None or "(少用)" not in (original.text or ""):
        return False
    for element in sentence.xpath(".//FORM"):
        if element.text:
            element.text = element.text.replace("?(少用).", "?")
            element.text = element.text.replace("?(少用)", "?")
    _append_note(original, "source annotation 少用: rarely used")
    _remove_phon(sentence)
    return True


def _replace_morphemes(word, forms_and_glosses):
    existing = word.findall("M")
    insert_at = word.index(existing[0]) if existing else len(word)
    tail = existing[-1].tail if existing else None
    for morph in existing:
        word.remove(morph)
    for index, (form, eng, zho) in enumerate(forms_and_glosses, start=1):
        morph = etree.Element("M", id=f"{word.get('id')}M{index}")
        etree.SubElement(morph, "FORM", kindOf="original").text = form
        etree.SubElement(morph, "FORM", kindOf="standard").text = form
        eng_t = etree.SubElement(morph, "TRANSL")
        eng_t.set(_XLANG, "eng")
        eng_t.text = eng
        zho_t = etree.SubElement(morph, "TRANSL")
        zho_t.set(_XLANG, "zho")
        zho_t.text = zho
        morph.tail = tail
        word.insert(insert_at + index - 1, morph)


