def _original_word_forms(sentence):
    return tuple(
        (_tier(word, "FORM", "original").text or "")
        for word in sentence.findall("W")
    )


def _set_sentence_form(sentence, value):
    for kind in ("original", "standard"):
        form = _tier(sentence, "FORM", kind)
        if form is not None:
            form.text = value


def _drop_all_words(sentence):
    for word in list(sentence.findall("W")):
        sentence.remove(word)


def _insert_after(sentence, variant):
    parent = sentence.getparent()
    parent.insert(parent.index(sentence) + 1, variant)


def _materialize_indexed_optional_words(
    relative, sentence, existing_ids, stats
):
    sid = sentence.get("id")
    case = INDEXED_OPTIONAL_WORDS.get((relative, sid))
    if case is None:
        return False
    expected_form, optionals = case
    original = _tier(sentence, "FORM", "original")
    marker = "source indexed optional notation materialized from " + expected_form
    if original is None:
        raise AssertionError(f"{relative}:{sid} has no original FORM")
    if original.text != expected_form:
        if marker in (original.get("notes") or ""):
            return False
        raise AssertionError(
            f"indexed optional FORM drifted for {relative}:{sid}; "
            f"expected {expected_form!r}, found {original.text!r}"
        )

    words = sentence.findall("W")
    for index, expected_word, _ in optionals:
        if index >= len(words):
            raise AssertionError(
                f"indexed optional W{index} missing for {relative}:{sid}"
            )
        actual = _tier(words[index], "FORM", "original")
        actual_text = actual.text if actual is not None else None
        if actual_text != expected_word:
            raise AssertionError(
                f"indexed optional W{index} drifted for {relative}:{sid}; "
                f"expected {expected_word!r}, found {actual_text!r}"
            )

    pristine = copy.deepcopy(sentence)
    variants = []
    groups = len(optionals)
    for mask in range(1 << groups):
        variant = sentence if mask == 0 else copy.deepcopy(pristine)
        choices = tuple(bool(mask & (1 << index)) for index in range(groups))
        rendered = expected_form
        for choice, (_, _, token) in zip(choices, optionals):
            notation = f"({token})"
            if rendered.count(notation) != 1:
                raise AssertionError(
                    f"optional notation {notation!r} drifted for "
                    f"{relative}:{sid}"
                )
            rendered = rendered.replace(notation, token if choice else "", 1)
        _set_sentence_form(variant, _normalize_sentence_form(rendered))

        for choice, (word_index, _, _) in sorted(
            zip(choices, optionals), key=lambda item: item[1][0], reverse=True
        ):
            if not choice:
                variant.remove(variant.findall("W")[word_index])

        new_sid = sid if mask == 0 else f"{sid}-opt{mask}"
        if mask:
            if new_sid in existing_ids:
                raise AssertionError(f"generated sentence id already exists: {new_sid}")
            existing_ids.add(new_sid)
            for audio in variant.xpath(".//AUDIO"):
                audio.getparent().remove(audio)
        _retarget_and_reindex(variant, new_sid)
        variant_original = _tier(variant, "FORM", "original")
        kept = [str(i + 1) for i, value in enumerate(choices) if value]
        omitted = [str(i + 1) for i, value in enumerate(choices) if not value]
        _append_note(
            variant_original,
            marker
            + "; kept group(s): " + (", ".join(kept) if kept else "none")
            + "; omitted group(s): "
            + (", ".join(omitted) if omitted else "none"),
        )
        _remove_phon(variant)
        variants.append(variant)

    parent = sentence.getparent()
    position = parent.index(sentence)
    for offset, variant in enumerate(variants[1:], start=1):
        parent.insert(position + offset, variant)
    stats["indexed optional source sentences expanded"] += 1
    stats["indexed optional readings emitted"] += len(variants)
    return True


def _materialize_rukai_optional_prefix(relative, sentence, existing_ids, stats):
    expected_relative, sid, expected_form = RUKAI_OPTIONAL_PREFIX
    if relative != expected_relative or sentence.get("id") != sid:
        return False
    original = _tier(sentence, "FORM", "original")
    marker = "source optional prefix has no aligned W/M analysis: (taka)"
    if original is None:
        raise AssertionError(f"{relative}:{sid} has no original FORM")
    if original.text != expected_form:
        if marker in (original.get("notes") or ""):
            return False
        raise AssertionError(
            f"Rukai optional-prefix FORM drifted for {sid}; expected "
            f"{expected_form!r}, found {original.text!r}"
        )
    expected_words = (
        "kai=su", "lri-maka-dreele", "kay", "kiucu-ane=li."
    )
    if _original_word_forms(sentence) != expected_words:
        raise AssertionError(
            f"Rukai optional-prefix W analysis drifted for {sid}: "
            f"{_original_word_forms(sentence)!r}"
        )

    full = copy.deepcopy(sentence)
    _set_sentence_form(sentence, expected_form.replace("(taka)", ""))
    _append_note(
        _tier(sentence, "FORM", "original"),
        marker + "; omitted reading retains the source W/M analysis",
    )
    _remove_phon(sentence)
    _retarget_and_reindex(sentence, sid)

    full_sid = f"{sid}-opt1"
    if full_sid in existing_ids:
        raise AssertionError(f"generated sentence id already exists: {full_sid}")
    existing_ids.add(full_sid)
    _set_sentence_form(full, expected_form.replace("(taka)", "taka"))
    _drop_all_words(full)
    for audio in full.xpath(".//AUDIO"):
        audio.getparent().remove(audio)
    _append_note(
        _tier(full, "FORM", "original"),
        marker + "; full reading emitted without W/M tiers to avoid invented alignment",
    )
    _remove_phon(full)
    _retarget_and_reindex(full, full_sid)
    _insert_after(sentence, full)
    stats["Rukai optional unaligned prefix expanded"] += 1
    stats["Rukai optional unaligned-prefix readings emitted"] += 2
    return True


