#!/usr/bin/env python3
"""Resolve the source parenthetical notation left after pipeline step 20.

The earlier optional-material steps handle whole optional words and clean
slash alternatives.  The NTU source also contains optional phonemes,
affixes, and phrases whose parentheses can cross morpheme or word element
boundaries.  POL-026 requires explicit optional material to become complete,
aligned sentence variants, not parenthesis-bearing W/M forms.

This script has three deliberately separate paths:

* balanced parentheses present in the sentence FORM are materialized as all
  source-explicit with/without combinations;
* balanced parentheses present only in W/M analysis are stripped while the
  sentence's attested surface is retained;
* a small source-located exception table repairs parser column shifts,
  annotation leakage, already-expanded slash choices, and three ambiguous
  cross-word spans for which an omitted analysis is not recoverable.

The original sentence becomes the all-omitted reading.  Additional readings
receive deterministic ``-optN`` suffixes.  AUDIO stays on the original only,
matching the convention used by ``split_optional_parentheticals.py``.  PHON
is removed only from changed sentences and is regenerated by the canonical
``add_phonology.py`` step immediately after this script in ``make.sh``.

Every exception is keyed by a stable source-derived sentence id.  The raw
JSON remains unchanged and therefore remains the primary audit witness.
The operation is deterministic and idempotent.
"""

