def _reorder_words(sentence, order):
    words = sentence.findall("W")
    if sorted(order) != list(range(len(words))):
        raise AssertionError(f"invalid W reorder {order!r}")
    insertion = sentence.index(words[0])
    for word in words:
        sentence.remove(word)
    for offset, index in enumerate(order):
        sentence.insert(insertion + offset, words[index])


def _materialize_rukai_positional_alternative(
    relative, sentence, existing_ids, stats
):
    expected_relative, sid, expected_form = RUKAI_POSITIONAL_ALTERNATIVE
    if relative != expected_relative or sentence.get("id") != sid:
        return False
    original = _tier(sentence, "FORM", "original")
    marker = "source positional alternative materialized from " + expected_form
    if original is None:
        raise AssertionError(f"{relative}:{sid} has no original FORM")
